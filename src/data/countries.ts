/** Nome italiano della nazione per ID paese PES; fallback "PES-{id}" se sconosciuto. */
export function nomeNazione(pesCountryId: number): string {
  return NAZIONI_PES[pesCountryId] ?? `PES-${pesCountryId}`;
}

/**
 * Normalizza una dicitura salvata: "PES-215" → "Italia".
 * Usato per i dati importati prima dell'introduzione della mappa nazioni.
 */
export function nomeNazioneDaStringa(valore: string): string {
  const match = /^PES-(\d+)$/.exec(valore);
  return match ? nomeNazione(Number(match[1])) : valore;
}
